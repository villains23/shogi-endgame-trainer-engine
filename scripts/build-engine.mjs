#!/usr/bin/env node
// Build the browser (WebAssembly, single-thread) YaneuraOu engine used by "ソフトで確認".
//
// This re-implements `make tournament COMPILER=em++ TARGET_CPU=WASM` for the
// YANEURAOU_ENGINE_NNUE_HALFKP_768X2_16_64 edition of shielune/YaneuraOu v9.60.2
// (commit ff8b229b2cffbdd4a2ded35509bf3a66ee2ff6a8), because GNU make / Docker were not
// available on the machine that produced the shipped binaries. Flags are copied from
// source/Makefile and script/wasm_build.js of that commit; every deviation is listed in
// MODIFICATIONS.md. The engine source itself is NOT modified.
//
// Requirements (see BUILD.md): Emscripten 5.0.5 activated (em++.py on PATH), Node.js >= 18, Python 3.
//
// Usage:
//   node scripts/build-engine.mjs --source <YaneuraOu checkout>/source --out <output dir> [--jobs N]
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createHash } from "node:crypto";
import { spawn, execFileSync } from "node:child_process";

const args = new Map();
for (let i = 2; i < process.argv.length; i += 2) args.set(process.argv[i].replace(/^--/, ""), process.argv[i + 1]);
const SRC = path.resolve(args.get("source") ?? "");
const OUT = path.resolve(args.get("out") ?? "");
if (!args.get("source") || !args.get("out") || !fs.existsSync(path.join(SRC, "Makefile"))) {
  console.error("usage: node scripts/build-engine.mjs --source <YaneuraOu checkout>/source --out <output dir> [--jobs N]");
  process.exit(2);
}
// The engine embeds the compile date (__DATE__) in the binary. Clang honours SOURCE_DATE_EPOCH, so pinning it
// makes the build bit-reproducible: this value (2026-10-03T12:00:00Z) reproduces the shipped binary, whose
// embedded date string is "Oct  3 2026". Override SOURCE_DATE_EPOCH to stamp a different date.
process.env.SOURCE_DATE_EPOCH ??= "1791028800";
const OBJ = path.join(OUT, "obj");
const ARCH = "HALFKP_768X2_16_64";
const EXPORT_NAME = "YaneuraOu_HalfKP768_noeval";
const BASENAME = "yaneuraou.nnue768";

// ---- 1. NNUE architecture header (generated by the repository's own script; not a source modification) ----
const python = ["python3", "python"].find((cmd) => {
  try {
    execFileSync(cmd, ["--version"], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
});
if (!python) throw new Error("python not found");
execFileSync(python, ["eval/nnue/architectures/nnue_arch_gen.py", ARCH, "eval/nnue/architectures"], { cwd: SRC, stdio: "inherit" });

// ---- 2. source list: base SOURCES of the Makefile + makebook + the NNUE edition block ----
const mk = fs.readFileSync(path.join(SRC, "Makefile"), "utf8").replace(/\r/g, "");
const baseBlock = mk.match(/^SOURCES\s*=\s*\\\n([\s\S]*?)\n\n/m)[1];
const sources = [...baseBlock.matchAll(/([\w\/\-\.]+\.cpp)/g)].map((m) => m[1]);
sources.push("book/makebook.cpp", "book/makebook2025.cpp");
{
  const start = mk.indexOf("eval/nnue/evaluate_nnue.cpp");
  const end = mk.indexOf("yaneuraou-search.cpp", start) + "yaneuraou-search.cpp".length;
  sources.push(...[...mk.slice(start, end).matchAll(/([\w\/\-\.]+\.cpp)/g)].map((m) => m[1]), "eval/nnue/wasm_simd.cpp");
}
for (const s of sources) if (!fs.existsSync(path.join(SRC, s))) throw new Error(`missing source ${s}`);

// ---- 3. flags (identical to the build that produced the shipped binaries) ----
const CPPFLAGS = [
  "-std=c++17", "-fno-exceptions", "-fno-rtti", "-Wextra", "-fpermissive", "-O2", "-DNDEBUG", "-Wno-unused-parameter",
  "-DUSE_WASM_SIMD", "-msimd128", "-DUSE_SSE42", "-msse4.2", "-s", "STRICT=1", "-DEM_MAXIMUM_MEMORY_SIZE=2147483648",
  "-DUNICODE", "-DNO_EXCEPTIONS",
  "-DYANEURAOU_ENGINE_NNUE", "-DYANEURAOU_ENGINE_NNUE_HALFKP_768X2_16_64", `-DNNUE_ARCHITECTURE_HEADER="architectures/${ARCH}.h"`,
  '-DTARGET_CPU="WASM"', "-DFOR_TOURNAMENT", "-flto",
];
const LDFLAGS = [
  "-flto", "-lpthread", "-v", "--pre-js", "wasm_pre.js",
  "-s", "MODULARIZE=1", "-s", `EXPORT_NAME=${EXPORT_NAME}`, "-s", "EXPORT_ES6=1", "-s", "ENVIRONMENT=web",
  "-s", "INCOMING_MODULE_JS_API=print,printErr,postRun,preRun,onAbort,onExit,onRuntimeInitialized,wasmBinary,locateFile,instantiateWasm,mainScriptUrlOrBlob,noInitialRun,noExitRuntime,arguments",
  "-s", "FILESYSTEM=1", "-s", "EXIT_RUNTIME=0", "-s", "EXPORTED_RUNTIME_METHODS=['FS','ccall']",
  "-s", "ALLOW_MEMORY_GROWTH=1", "-s", "INITIAL_MEMORY=268435456", "-s", "MAXIMUM_MEMORY=2147483648", "-s", "STACK_SIZE=67108864",
  "--closure", "0",
];

// Run em++.py directly with python (no shell), so that quotes inside -D macros reach the compiler
// unchanged on every platform. em++.py sits in the Emscripten directory that `emsdk_env` puts on PATH.
const empp = (process.env.PATH ?? "")
  .split(path.delimiter)
  .map((dir) => path.join(dir, "em++.py"))
  .find((candidate) => fs.existsSync(candidate));
if (!empp) throw new Error("em++.py not found on PATH (activate Emscripten 5.0.5 first, see BUILD.md)");
const emsdkPython = process.env.EMSDK_PYTHON ?? python;

function run(cmdArgs, label) {
  return new Promise((resolve, reject) => {
    const child = spawn(emsdkPython, [empp, ...cmdArgs], { cwd: SRC, stdio: ["ignore", "pipe", "pipe"] });
    let output = "";
    child.stdout.on("data", (d) => (output += d));
    child.stderr.on("data", (d) => (output += d));
    child.on("close", (code) => (code === 0 ? resolve(output) : reject(new Error(`${label} failed (${code})\n${output.slice(-3000)}`))));
  });
}

fs.mkdirSync(OBJ, { recursive: true });
const jobs = sources.map((s) => ({ s, o: path.join(OBJ, s.replace(/\.cpp$/, ".o").replace(/\//g, "__")) }));
const parallel = Number(args.get("jobs") ?? Math.max(2, os.cpus().length - 1));
console.log(`[build] ${sources.length} sources, parallel=${parallel}`);
let next = 0;
let done = 0;
await Promise.all(
  Array.from({ length: parallel }, async () => {
    while (next < jobs.length) {
      const job = jobs[next++];
      await run([...CPPFLAGS, "-o", job.o, "-c", path.join(SRC, job.s)], job.s);
      if (++done % 10 === 0 || done === jobs.length) console.log(`[build] compiled ${done}/${jobs.length}`);
    }
  }),
);

fs.mkdirSync(OUT, { recursive: true });
console.log("[build] linking");
await run([...jobs.map((j) => j.o), "-o", path.join(OUT, `${BASENAME}.js`), ...LDFLAGS, ...CPPFLAGS], "link");

for (const file of [`${BASENAME}.js`, `${BASENAME}.wasm`]) {
  const bytes = fs.readFileSync(path.join(OUT, file));
  console.log(`${createHash("sha256").update(bytes).digest("hex")}  ${file}  (${bytes.length} bytes)`);
}
